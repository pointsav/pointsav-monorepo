# One-off generator for src/tables.rs. Reads Perl's bundled Unicode database
# (Unicode::UCD) and writes a start-of-range table of effective line-break classes.
# Usage: perl gen/make_tables.pl > src/tables.rs
use strict;
use warnings;
use Unicode::UCD qw(prop_invmap);

sub load {
    my ($p) = @_;
    my ($l, $v, $f, $d) = prop_invmap($p);
    return ($l, $v);
}
sub look {
    my ($l, $v, $cp) = @_;
    my ($lo, $hi) = (0, scalar(@$l) - 1);
    while ($lo < $hi) {
        my $m = ($lo + $hi + 1) >> 1;
        if ($l->[$m] <= $cp) { $lo = $m } else { $hi = $m - 1 }
    }
    return $v->[$lo];
}
my ($lbl, $lbv) = load("Line_Break");
my ($gcl, $gcv) = load("General_Category");
my ($eal, $eav) = load("East_Asian_Width");
my ($epl, $epv) = load("Extended_Pictographic");

# Breakpoints: union of all invmap starts.
my %pts;
for my $l ($lbl, $gcl, $eal, $epl) { $pts{$_} = 1 for grep { $_ <= 0x10FFFF } @$l }
my @starts = sort { $a <=> $b } keys %pts;

my @out;
my $prev;
for my $cp (@starts) {
    my $lb = look($lbl, $lbv, $cp);
    my $gc = look($gcl, $gcv, $cp);
    my $ea = look($eal, $eav, $cp);
    my $ep = look($epl, $epv, $cp);
    my $c = $lb;
    if ($lb eq 'SA') { $c = ($gc eq 'Mn' || $gc eq 'Mc') ? 'CM' : 'AL' }   # LB1
    elsif ($lb eq 'QU') { $c = $gc eq 'Pi' ? 'QU_PI' : $gc eq 'Pf' ? 'QU_PF' : 'QU' }
    elsif ($lb eq 'OP') { $c = ($ea eq 'F' || $ea eq 'W' || $ea eq 'H') ? 'OP_EA' : 'OP' }
    elsif ($lb eq 'CP') { $c = ($ea eq 'F' || $ea eq 'W' || $ea eq 'H') ? 'CP_EA' : 'CP' }
    elsif ($lb eq 'ID' && $ep eq 'Y' && $gc eq 'Cn') { $c = 'ID_PICT' }       # LB30b
    next if defined $prev && $prev eq $c;
    push @out, [$cp, $c];
    $prev = $c;
}
my $ver = Unicode::UCD::UnicodeVersion();
print "// SPDX-License-Identifier: Apache-2.0\n";
print "// SPDX-FileCopyrightText: 2026 Woodfine Capital Projects Inc.\n\n";
print "//! GENERATED by gen/make_tables.pl - do not edit by hand.\n";
print "//!\n//! Source: Perl Unicode::UCD (perl $^V), Unicode $ver properties Line_Break,\n";
print "//! General_Category, East_Asian_Width, Extended_Pictographic. SA is resolved by LB1\n";
print "//! (Mn/Mc to CM, else AL); QU is split by Pi/Pf; OP and CP are split by East Asian Width\n";
print "//! F/W/H (LB30); unassigned Extended_Pictographic code points become ID_PICT (LB30b).\n\n";
print "use crate::class::Lb::{self, *};\n\n";
print "/// Unicode version of the property data below.\npub const UNICODE_VERSION: &str = \"$ver\";\n\n";
print "/// Sorted `(first code point, class)`; each entry holds until the next entry starts.\n";
printf "pub(crate) static LB_TABLE: [(u32, Lb); %d] = [\n", scalar @out;
my @row;
for my $e (@out) { push @row, sprintf("(0x%X, %s)", $e->[0], $e->[1]) }
while (@row) { my @c = splice(@row, 0, 5); print "    ", join(", ", @c), ",\n" }
print "];\n";
